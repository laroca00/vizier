export type Strengths = { strengths: StrengthKey[]; weaknesses: WeaknessKey[] };

function parse(line: string): Strengths {
  const [good = "", bad = ""] = line.split("|");
  return {
    strengths: good.trim().split(/\s+/).filter(Boolean) as StrengthKey[],
    weaknesses: bad.trim().split(/\s+/).filter(Boolean) as WeaknessKey[],
  };
}

/** The hand-kept strengths and weaknesses of a champion, or null for one not written up yet. */
export function strengthsOf(championId: string): Strengths | null {
  const line = TABLE[championId];
  return line ? parse(line) : null;
}

